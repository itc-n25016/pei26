a = 0b11010 #　Pythonでは2進数の整数リテラルの先頭に「0b」をつける
b = 0b10100
c = a & b # aとbのビットごとのAND演算
d = a | b # aとbのビットごとのOR演算
c >>= 2 # cを右に2ビットシフトした結果をcに代入
e = d - c
print(f'{e:b}') # f文字列を使って変数eを2進数(binary)で表現

